function New-WinForgeAutounattend {
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSReviewUnusedParameter', 'NoDiskWipe', Justification = 'Accepted for backward compatibility; disk wipe is never generated.')]
    param(
        [Parameter(Mandatory)] [string] $OutFile,
        [string] $ComputerName = 'WINFORGE-PC',
        [string] $Locale = 'en-US',
        [string] $TimeZone = 'UTC',
        [string] $UserName = 'WinForge',
        [Alias('Profile')] [string] $ProfileName = 'Recommended',
        [ValidateSet('amd64','arm64')] [string] $Architecture = $(if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'arm64' } else { 'amd64' }),
        # Kept for compatibility: disk wiping is never generated by default.
        [switch] $NoDiskWipe,
        [switch] $IncludeDiskWipe
    )

    if ($IncludeDiskWipe) {
        # A correct unattended layout needs a DiskID, WillWipeDisk and the EFI/MSR/Windows
        # partitions for UEFI. Until that is implemented and tested, refuse rather than
        # emit a layout that wipes a disk and then fails to install.
        throw 'Unattended disk partitioning is not implemented. Partition the disk in Setup, or let Rufus create the media.'
    }
    if (Test-Path -LiteralPath $OutFile) { throw "Refusing to overwrite existing file: $OutFile" }
    if ($ComputerName -notmatch '^(?=.*[A-Za-z-])[A-Za-z0-9-]{1,15}$') { throw "Invalid computer name '$ComputerName' (1-15 letters, digits or hyphens, not all digits)." }
    if ($UserName -notmatch '^[A-Za-z0-9._-]{1,20}$') { throw "Invalid user name '$UserName'." }
    if ($Locale -notmatch '^[a-z]{2,3}(-[A-Za-z]{2,4}){1,2}$') { throw "Invalid locale '$Locale'." }
    try { [void][TimeZoneInfo]::FindSystemTimeZoneById($TimeZone) } catch { throw "Unknown Windows time zone ID '$TimeZone'." }
    if ($ProfileName -notin @('Minimal','Recommended','Aggressive')) { throw "Unknown profile '$ProfileName'." }

    $esc = { param($s) [Security.SecurityElement]::Escape($s) }
    $arch = $Architecture
    $comp = "processorArchitecture=""$arch"" publicKeyToken=""31bf3856ad364e35"" language=""neutral"" versionScope=""nonSxS"""

    # FirstLogonCommands: run WinForge only if Setup copied it ($OEM$ is not automated
    # yet), force a password change because the account starts with a blank password,
    # and delete Setup's cached copies of this answer file.
    $applyCmd = "cmd /c if exist C:\WinForge\WinForge.ps1 powershell -NoProfile -ExecutionPolicy Bypass -File C:\WinForge\WinForge.ps1 -Command Apply -Profile $ProfileName -Force"
    $pwCmd    = "net user $UserName /logonpasswordchg:yes"
    $cleanCmd = 'cmd /c del /f /q %WINDIR%\Panther\unattend.xml %WINDIR%\Panther\unattend-original.xml %WINDIR%\System32\Sysprep\unattend.xml'

    $xmlLines = @(
        '<?xml version="1.0" encoding="utf-8"?>',
        '<unattend xmlns="urn:schemas-microsoft-com:unattend" xmlns:wcm="http://schemas.microsoft.com/WMIConfig/2002/State" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance">',
        '  <settings pass="windowsPE">',
        "    <component name=""Microsoft-Windows-International-Core-WinPE"" $comp>",
        "      <SetupUILanguage><UILanguage>$(& $esc $Locale)</UILanguage></SetupUILanguage>",
        "      <InputLocale>$(& $esc $Locale)</InputLocale><SystemLocale>$(& $esc $Locale)</SystemLocale><UILanguage>$(& $esc $Locale)</UILanguage><UserLocale>$(& $esc $Locale)</UserLocale>",
        '    </component>',
        "    <component name=""Microsoft-Windows-Setup"" $comp>",
        '      <UserData><AcceptEula>true</AcceptEula><FullName>WinForge</FullName><Organization>WinForge</Organization></UserData>',
        '    </component>',
        '  </settings>',
        '  <settings pass="oobeSystem">',
        "    <component name=""Microsoft-Windows-Shell-Setup"" $comp>",
        "      <ComputerName>$(& $esc $ComputerName)</ComputerName>",
        "      <TimeZone>$(& $esc $TimeZone)</TimeZone>",
        '      <OOBE><HideEULAPage>true</HideEULAPage><HideOEMRegistrationScreen>true</HideOEMRegistrationScreen><HideOnlineAccountScreens>true</HideOnlineAccountScreens><HideWirelessSetupInOOBE>true</HideWirelessSetupInOOBE><ProtectYourPC>3</ProtectYourPC></OOBE>',
        "      <UserAccounts><LocalAccounts><LocalAccount wcm:action=""add""><Name>$(& $esc $UserName)</Name><Group>Administrators</Group><Password><Value></Value><PlainText>true</PlainText></Password></LocalAccount></LocalAccounts></UserAccounts>",
        "      <AutoLogon><Enabled>true</Enabled><Username>$(& $esc $UserName)</Username><Password><Value></Value><PlainText>true</PlainText></Password><LogonCount>1</LogonCount></AutoLogon>",
        '      <FirstLogonCommands>',
        "        <SynchronousCommand wcm:action=""add""><Order>1</Order><CommandLine>$(& $esc $applyCmd)</CommandLine><Description>WinForge profile</Description></SynchronousCommand>",
        "        <SynchronousCommand wcm:action=""add""><Order>2</Order><CommandLine>$(& $esc $pwCmd)</CommandLine><Description>Require a password at next sign-in</Description></SynchronousCommand>",
        "        <SynchronousCommand wcm:action=""add""><Order>3</Order><CommandLine>$(& $esc $cleanCmd)</CommandLine><Description>Remove cached answer files</Description></SynchronousCommand>",
        '      </FirstLogonCommands>',
        '    </component>',
        '  </settings>',
        '</unattend>'
    )
    $xml = $xmlLines -join "`r`n"
    [void]([xml]$xml)   # refuse to write anything Windows Setup could not parse

    Set-Content -LiteralPath $OutFile -Value $xml -Encoding UTF8
    Write-WinForgeLog -Level Warn -Message "Answer file written to $OutFile. The '$UserName' administrator starts with a blank password and must set one at the next sign-in. Keep the USB copy private."
    return [pscustomobject]@{
        OutFile = $OutFile; Profile = $ProfileName; DiskWipe = $false; Architecture = $arch
        Note = 'Copy WinForge to $OEM$\$1\WinForge on the USB so Setup places it at C:\WinForge; otherwise step 1 is skipped.'
    }
}

function Test-WinForgePortable {
    param($Context)
    return [pscustomobject]@{
        Portable   = $Context.IsPortable
        StateRoot  = $Context.StateRoot
        Writable   = (Test-Path -LiteralPath $Context.StateRoot -PathType Container)
    }
}

function Invoke-WinForgeDeployModule {
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSReviewUnusedParameter', 'Context', Justification = 'Uniform module signature.')]
    param($Context,[string] $OutFile, [Alias('Profile')] [string] $ProfileName = 'Recommended')
    if (-not $OutFile) { throw 'Provide -OutFile for the autounattend.xml path.' }
    New-WinForgeAutounattend -OutFile $OutFile -Profile $ProfileName
}
